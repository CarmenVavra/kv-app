        <h1 class="font-serif font-semibold text-text mb-6" style="font-size: clamp(26px, 4vw, 36px); line-height: 1.2; text-wrap: balance;">
            Stresssignale deuten: Höre auf das Flüstern deines Hundes
        </h1>

        <div class="flex flex-col gap-5 text-[color:var(--color-text-muted-2)] text-[15.5px] leading-relaxed">
            <p>
                Bevor ein Hund bellend und knurrend in die Leine springt, vergeht meistens viel Zeit, in der er
                versucht, mit seiner Umwelt zu kommunizieren. Er flüstert, bevor er schreit. Für uns Menschen sind diese
                ersten, feinen Stress- und Beschwichtigungssignale im Alltag jedoch oft schwer zu erkennen. Wer die
                Sprache seines Hundes lesen lernt, kann Konflikte entschärfen, lange bevor die Situation eskaliert.
            </p>

            <h3 class="font-serif font-semibold text-text text-lg mt-3">Die ersten Anzeichen von Unbehagen</h3>
            <p>
                Wenn ein Hund auf Distanz einen anderen Hund bemerkt und sich unwohl fühlt, greift er auf ein Repertoire
                an körpereigenen Signalen zurück, um die Situation zu befrieden oder seinen Stress zu kompensieren:
            </p>
            <ul class="flex flex-col gap-2.5 list-disc pl-5">
                <li><strong class="text-text">Züngeln / Lippenlecken:</strong> Der Hund fährt sich kurz mit der Zungenspitze über den Fang, ohne dass Futter im Spiel ist.</li>
                <li><strong class="text-text">Gähnen:</strong> Ein plötzliches Gähnen in einer Begegnungssituation ist selten Müdigkeit, sondern ein deutliches Zeichen von innerer Anspannung.</li>
                <li><strong class="text-text">Blickmeiden / Abwenden:</strong> Der Hund dreht den Kopf leicht weg oder schaut bewusst am anderen Hund vorbei, um zu signalisieren: <em>„Ich suche keinen Streit.“</em></li>
            </ul>

            <h3 class="font-serif font-semibold text-text text-lg mt-3">Wenn der Stresspegel steigt: Das Einfrieren</h3>
            <p>
                Wird die Distanz zum anderen Hund geringer und der Stress größer, verändert sich die Körpersprache
                drastisch. Viele Hunde fallen in ein sogenanntes „Freeze“ (Einfrieren). Die gesamte Muskulatur spannt
                sich an, die Rute wird steif getragen und der Blick fixiert den Artgenossen unbeweglich. In dieser Phase
                ist der Hund meist mental nicht mehr ansprechbar. Das darauffolgende Vorpreschen in die Leine ist dann
                nur noch das finale Ventil, um den aufgestauten Druck zu entladen.
            </p>

            <h3 class="font-serif font-semibold text-text text-lg mt-3">Wie du dieses Wissen im Alltag nutzt</h3>
            <p>
                Beobachte deinen Hund bei den nächsten Spaziergängen genau. Sobald du ein feines Signal wie das
                Lippenlecken oder ein steiferes Gangbild bemerkst, ist das dein Startsignal zum Handeln: Vergrößere
                sofort aktiv den Abstand zum anderen Mensch-Hund-Team. Biege in eine Seitenstraße ab, gehe einen großen
                Bogen oder drehe um. Indem du das Flüstern deines Hundes ernst nimmst, vermittelst du ihm die
                wichtigste Botschaft überhaupt: <em>Du bist sicher bei mir, ich regle das für uns.</em>
            </p>
